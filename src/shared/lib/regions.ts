const ALL_SIGUNGU: Sigungu[] = Object.values(SIGUNGU).flat()

/** 시군구 코드로 { 시도명, 시군구명, 시도코드 } 조회 */
export function findRegion(sigunguCode: string) {
  const sgg = ALL_SIGUNGU.find((r) => r.code === sigunguCode)
  if (!sgg) return null
  const sido = SIDO.find((s) => s.code === sgg.sidoCode)
  return { sidoCode: sgg.sidoCode, sidoName: sido?.name ?? '', sigunguCode: sgg.code, sigunguName: sgg.name }
}

/** '서울특별시 마포구' 같은 전체 이름 */
export function regionFullName(sigunguCode: string): string {
  const r = findRegion(sigunguCode)
  return r ? `${r.sidoName} ${r.sigunguName}` : ''
}

